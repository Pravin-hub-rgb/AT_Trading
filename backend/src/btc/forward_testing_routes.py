"""/api/btc/forward - forward-testing dashboard data source.

Serves the committed artifact that
backtest/tests/exp_forward_eval.py writes. Same pattern as btc_results_routes:
read a JSON file, cache by mtime, never execute the engine in-process.

The artifact lives at backtest/tests/_forward_eval.json and is regenerated by:
    cd backtest && python tests/exp_forward_eval.py

Forward data extension is done by:
    cd backtest && python tests/exp_append_forward_data.py --tf 15m,1h,1m

Contract: forward data (post 2026-09-13 10:03 IST) is never searched or tuned.
See backtest/docs/learn/01_rules/FORWARD_BOUNDARY.md for the full methodology.
"""
from __future__ import annotations

import json
import os

from fastapi import APIRouter, HTTPException
from fastapi.responses import JSONResponse

router = APIRouter(prefix="/api/btc", tags=["forward"])

_HERE = os.path.dirname(os.path.abspath(__file__))
_BACKEND = os.path.abspath(os.path.join(_HERE, os.pardir, os.pardir))
ARTIFACT = os.path.join(_BACKEND, os.pardir, "backtest", "tests", "_forward_eval.json")

_cache: dict = {"data": None, "mtime": None}


def _load(force: bool = False) -> dict:
    if not os.path.exists(ARTIFACT):
        raise HTTPException(
            status_code=503,
            detail=(
                "forward eval artifact missing. Run: "
                "cd backtest && python tests/exp_forward_eval.py"
            ),
        )
    mtime = os.path.getmtime(ARTIFACT)
    if force or _cache["data"] is None or _cache["mtime"] != mtime:
        with open(ARTIFACT, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        _cache["data"] = data
        _cache["mtime"] = mtime
    return _cache["data"]


@router.get("/forward")
def get_forward_summary(refresh: bool = False):
    """Forward-test summary for all candidates.

    Returns the cutoff, candidate list with pre-cutoff vs forward stats,
    verdicts per R1-R5 rules, and trade logs for each candidate.
    """
    data = _load(force=refresh)
    out = dict(data)
    out["artifact_mtime"] = _cache["mtime"]
    out["candidate_count"] = len(data.get("candidates", {}))
    return JSONResponse(out)


@router.get("/forward/{book_key}")
def get_forward_book(book_key: str, refresh: bool = False):
    """Detailed forward-test results for one candidate.

    `book_key` matches the keys in the CANDIDATES dict of exp_forward_eval.py,
    e.g. "MCLOFF_HTF15", "HTF15_TSKIP6".
    """
    data = _load(force=refresh)
    candidates = data.get("candidates", {})
    if book_key not in candidates:
        raise HTTPException(
            status_code=404,
            detail="unknown forward candidate: %s (available: %s)" % (
                book_key, ", ".join(candidates.keys())
            ),
        )
    result = candidates[book_key]
    result["cutoff_ist"] = data.get("cutoff_ist")
    result["cutoff_ts"] = data.get("cutoff_ts")
    result["combined_15m_bars"] = data.get("combined_15m_bars")
    result["combined_1h_bars"] = data.get("combined_1h_bars")
    result["fine_1m_bars"] = data.get("fine_1m_bars")
    result["artifact_mtime"] = _cache["mtime"]
    return JSONResponse(result)
