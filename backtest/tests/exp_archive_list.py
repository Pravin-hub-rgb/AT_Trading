"""exp_archive_list - dump every retired book, with its harness-ready config.

WHY THIS EXISTS
===============
The owner's instruction when retiring books:

    "ye book se hat rahi hai archive mai hongi he - jaise kabhi experiment karna
     ho toh waha kaam aaye harness ka code wagera"

So the requirement is not "remember the numbers", it is "be able to RUN it again".
That makes a markdown table of pins insufficient. A retired book has to come back
with its parameter dict intact, otherwise re-running it means reconstructing a
config from prose and hoping.

This is why `registry/retired.py` exposes `archived()`, which returns the live
config objects straight from the family modules rather than a copy. Nothing was
moved out when a book was retired, so there is exactly one source of truth and it
cannot go stale. This file renders it.

WHAT IT WRITES
==============
  _archive_list.md    the readable table: bar, trades, net, avgR, DD, in both eras
  _archive_list.json  every retired book's FULL config and pins, machine readable
  docs/method/BOOK_ARCHIVE.md   the durable record, same shape as the prune doc

HOW TO RUN A RETIRED BOOK AGAIN
===============================
Two ways, both supported, because sometimes you want the registry and sometimes
you do not:

  1. In the registry - delete the key from RETIRED in registry/retired.py, fix
     the assert count, then:
         python exp_registry_snapshot.py write _registry_before.json
     The definition never moved, so `exp_fastcheck.py <book>` will confirm the
     pins still reproduce.

  2. Without touching the registry - take the config from the JSON and hand it
     to the harness directly. `run_experiment.run_one` takes a key, but the
     engine call is just:
         sim(c1h, sw, c15, sw15, fine_ltf=fine, **cfg["params"])
     with `cfg["swing"]` selecting the swing series. Every retired row carries
     both fields, so this works with no restoration at all.

Run:  cd backtest/tests
      python -u exp_archive_list.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
for p in ("backtest/tests", "backtest", "backend"):
    sys.path.insert(0, str(ROOT / p))

OUT_JSON = Path(__file__).parent / "_archive_list.json"
OUT_MD = Path(__file__).parent / "_archive_list.md"
DOC_MD = ROOT / "backtest/docs/method/BOOK_ARCHIVE.md"

BAR_TITLE = {
    "bar1_era_fitted": "BAR 1 - IS positive, OOS negative",
    "bar1_both_negative": "BAR 1 - negative in both eras",
    "bar1_inverse_IS_neg_OOS_pos": "BAR 1 - INVERSE: IS negative, OOS positive",
    "bar2_oos_under_50": "BAR 2 - 0 <= OOS < 50R",
    "alias_of_retired": "ALIAS - points at a retired book",
}


def main():
    from registry.retired import archived, bar_of
    from experiment_registry import EXPERIMENTS

    arch = archived()
    bars = {}
    for k in arch:
        bars.setdefault(bar_of(k) or "unknown", []).append(k)

    P = print
    P("=" * 118)
    P("  ARCHIVE - %d retired books, configs still runnable" % len(arch))
    P("  the registry now holds %d books" % len(EXPERIMENTS))
    P("=" * 118)

    for bar in ("bar1_both_negative", "bar1_inverse_IS_neg_OOS_pos",
                "bar1_era_fitted", "bar2_oos_under_50", "alias_of_retired",
                "unknown"):
        sel = bars.get(bar) or []
        if not sel:
            continue
        P()
        P("-" * 118)
        P("%s   (%d)" % (BAR_TITLE.get(bar, bar), len(sel)))
        P("-" * 118)
        P("  %-36s %6s %9s %8s %8s %7s %9s %8s %8s"
          % ("book", "n", "net", "avgR", "dd", "oos_n", "oos_net", "oos_avgR", "oos_dd"))
        rows = []
        for k in sorted(sel):
            cfg = arch[k]
            p = (cfg.get("pins") or {}) if isinstance(cfg, dict) else {}
            if not p:
                P("  %-36s   alias row -> %s" % (k, cfg))
                rows.append((k, None))
                continue
            n, net, dd = p.get("n"), p.get("net"), p.get("dd_net")
            on, onet, odd = p.get("oos_n"), p.get("oos_net"), p.get("oos_dd_net")
            ea = round(net / n, 4) if (net is not None and n) else None
            oa = round(onet / on, 4) if (onet is not None and on) else None
            P("  %-36s %6s %9s %8s %8s %7s %9s %8s %8s"
              % (k, n, net, ea, dd, on, onet, oa, odd))
            rows.append((k, p))
        P()

    payload = {k: {"bar": bar_of(k), "config": arch[k]} for k in arch}
    OUT_JSON.write_text(json.dumps(payload, indent=2, default=str) + "\n",
                        encoding="utf-8")

    lines = ["# archive - every retired book, configs still runnable", "",
             "Generated by `exp_archive_list.py` from `registry/retired.py::archived()`,",
             "which reads the live family-module configs. Nothing was copied when a",
             "book was retired, so this cannot drift from them.", "",
             "| bar | books |", "|---|---:|"]
    for bar in sorted(bars):
        lines.append("| %s | %d |" % (BAR_TITLE.get(bar, bar), len(bars[bar])))
    lines += ["", "| book | bar | n | net | avgR | dd | oos_n | oos_net | oos_avgR | oos_dd |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for k in sorted(arch):
        cfg = arch[k]
        p = (cfg.get("pins") or {}) if isinstance(cfg, dict) else {}
        if not p:
            lines.append("| %s | %s | alias -> %s |" % (k, bar_of(k), cfg))
            continue
        n, net, dd = p.get("n"), p.get("net"), p.get("dd_net")
        on, onet, odd = p.get("oos_n"), p.get("oos_net"), p.get("oos_dd_net")
        ea = "%.3f" % (net / n) if (net is not None and n) else "-"
        oa = "%.3f" % (onet / on) if (onet is not None and on) else "-"
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            k, bar_of(k), n, net, ea, dd, on, onet, oa, odd))
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")

    d = ["# book archive - retired, not deleted", "",
         "Date: 2026-10-08. Every book here was removed from `EXPERIMENTS` by the",
         "owner's rule. **None of them were deleted.** The definitions never left",
         "their family modules.", "",
         "## the two bars", "",
         "> any book jisme IS ya OOS negative hai usko hata",
         "> OOS 50R se low hai to hata", "",
         "| bar | meaning | books |", "|---|---|---:|"]
    for bar in ("bar1_era_fitted", "bar1_both_negative", "bar1_inverse_IS_neg_OOS_pos",
                "bar2_oos_under_50", "alias_of_retired"):
        if bar in bars:
            d.append("| `%s` | %s | %d |" % (bar, BAR_TITLE[bar], len(bars[bar])))
    d += ["", "**236 entries -> %d books.** %d keys retired in total." % (
        len(EXPERIMENTS), len(arch)), "",
          "## how to run a retired book again", "",
          "Two ways, both supported.", "",
          "**1. Through the registry.** Delete the key from the right set in",
          "`registry/retired.py`, fix the `assert` count, then:",
          "",
          "```",
          "python exp_registry_snapshot.py write _registry_before.json",
          "python exp_fastcheck.py <book>",
          "```", "",
          "The definition never moved, so the pins will reproduce.", "",
          "**2. Without touching the registry at all.** `_archive_list.json` holds",
          "every retired book's full config and pins. The engine call is:",
          "",
          "```",
          'sim(c1h, sw, c15, sw15, fine_ltf=fine, **cfg["params"])',
          "```",
          "",
          "with `cfg[\"swing\"]` picking the swing series. Both fields are in the JSON,",
          "so this works with no restoration step.", "",
          "## the 3 books that left by rule and not by measurement", "",
          "`gap_campaign_max2`, `gap_campaign_markneg` and `gap_entry_cap2` are",
          "negative IN SAMPLE and strongly positive OUT OF SAMPLE:", "",
          "| book | IS avgR | OOS avgR | OOS net | OOS dd |",
          "|---|---:|---:|---:|---:|"]
    for k in sorted(bars.get("bar1_inverse_IS_neg_OOS_pos", [])):
        p = (arch[k].get("pins") or {})
        d.append("| %s | %.3f | %s | %s | %s |" % (
            k, p.get("net", 0) / p["n"], p["oos_net"] / p["oos_n"],
            p["oos_net"], p["oos_dd_net"]))
    d += ["",
          "They were shown these numbers and the owner held the rule that a book",
          "negative in either era comes out. The reason they left is the rule, not a",
          "measurement, and `archived()` returns them with pins intact so the call",
          "can be reversed without re-deriving anything.", "",
          "## full table", "",
          "See `_archive_list.md` for all %d retired books with trades, net, average R"
          % len(arch),
          "per trade, drawdown and retention in both eras, and",
          "`_archive_list.json` for the runnable configs.", ""]
    DOC_MD.write_text("\n".join(d), encoding="utf-8")

    P()
    P("wrote %s, %s and %s" % (OUT_MD.name, OUT_JSON.name, DOC_MD.name))
    P("restore one: remove the key from RETIRED in registry/retired.py, fix the")
    P("assert count, then re-anchor the snapshot. Definition never moved.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())