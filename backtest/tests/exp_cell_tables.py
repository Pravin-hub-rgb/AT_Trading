"""exp_cell_tables - print the metric tables, one section each.

WHY A SEPARATE FILE
==================
exp_cell_full.py prints four columns side by side and dumps everything at once.
That is the right format for checking a number against the harness, and the wrong
one for reading. Four books in four columns invites the reader to compare them as
if they were peers, and they are not - three of them were attempts to make the
fourth into something else.

So this prints one table per book, plus a short header for each saying what that
book IS and whether it is real. Same numbers, same source JSON, no new
measurement. If a number here disagrees with _cell_full.md it is a printing bug,
not a new finding.

Run:  cd backtest/tests
      python -u exp_cell_tables.py            # to the terminal
      python -u exp_cell_tables.py --write    # also write the .md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
SRC = HERE / "_cell_full.json"
OUT = HERE / "_cell_tables.md"

BOOKS = ["BOOK", "CELL", "GATE", "UNION"]

WHAT = {
    "BOOK": ("fsent_champ_long as it ships, mode=atr_high.",
             "REAL. This is the book you trade. Nothing in this work changed it."),
    "CELL": ("Not a book. The subset of BOOK's trades that fall in the measured "
             "regime (chop>58 and atrp<0.65). Shown because it looked good.",
             "REAL AS A MEASUREMENT, useless as a book. 42 trades OOS, and its "
             "edge is a right tail rather than a win rate."),
    "GATE": ("A new book: BOOK rebuilt to take only the cell trades, "
             "mode=chop_hi_atr_lo_gate.",
             "ATTEMPT. Failed. 58 OOS trades cannot wait for the tail the cell "
             "depends on; win rate collapses to 20.7%."),
    "UNION": ("A new book: BOOK plus the cell as extra permission, "
              "mode=atr_high_or_chop_hi_atr_lo.",
              "ATTEMPT. Failed. The additions are -19.0R out of sample."),
}

METRICS = [
    ("n", "trades"),
    ("n_wins", "winning trades"),
    ("n_losses", "losing trades"),
    ("wr", "WIN RATE %"),
    ("net", "NET R"),
    ("avgR", "mean R per trade"),
    ("median", "median R"),
    ("stdR", "std of R"),
    ("avg_win", "avg winning trade"),
    ("avg_loss", "avg losing trade"),
    ("payoff", "payoff ratio"),
    ("pf", "PROFIT FACTOR"),
    ("max_dd", "MAX DRAWDOWN"),
    ("dd_dur", "drawdown duration (bars)"),
    ("ulcer", "ulcer index"),
    ("sortino", "sortino"),
    ("calmar", "calmar"),
    ("max_streak", "LONGEST LOSING RUN"),
    ("pos_month_pct", "positive months %"),
    ("worst_month", "worst month R"),
    ("top5_share_pct", "top-5 trades as % of net"),
    ("trimmed", "trimmed mean R"),
]

DIST = [
    ("mean", "mean R"),
    ("median", "median R"),
    ("std", "std"),
    ("p10", "10th percentile R"),
    ("p90", "90th percentile R"),
    ("max", "best trade R"),
    ("win_pct", "win rate %"),
    ("avg_win", "avg winning trade"),
    ("avg_loss", "avg losing trade"),
    ("largest_win_share", "best trade as % of net"),
    ("without_top1", "net without best trade"),
    ("without_top3", "net without top 3"),
    ("losses_over_1R", "trades losing more than 1R"),
    ("wins_over_3R", "trades winning more than 3R"),
]


def fmt(v):
    if v is None:
        return "-"
    if isinstance(v, float):
        return "%.2f" % v if abs(v) >= 1 else "%.3f" % v
    return str(v)


def main() -> int:
    if not SRC.exists():
        print("run exp_cell_full.py first - %s does not exist" % SRC.name)
        return 1
    data = json.loads(SRC.read_text(encoding="utf-8"))
    eras = data["eras"]

    out = []
    w = out.append

    w("# The four books - %s" % data["book"])
    w("")
    w("Generated by `exp_cell_tables.py` from `_cell_full.json`. Same numbers as")
    w("`_cell_full.md`; this file separates them so they are not read as peers.")
    w("Post-C17 engine, both eras.")
    w("")
    w("## The short version")
    w("")
    w("| | what it is | status |")
    w("|---|---|---|")
    for b in BOOKS:
        w("| **%s** | %s | %s |" % (b, WHAT[b][0], WHAT[b][1]))
    w("")
    w("Three of these were attempts to make BOOK trade the cell. None worked.")
    w("**BOOK is unchanged and is the book you trade.**")
    w("")

    for era, label in (("is", "IN SAMPLE"), ("oos", "OUT OF SAMPLE")):
        e = eras[era]
        w("## %s" % label)
        w("")
        for b in BOOKS:
            m = e["sets"][b]
            d = e["dist"][b]
            w("### %s" % b)
            w("")
            w("%s" % WHAT[b][0].rstrip(".") + ".")
            w("")
            w("| metric | value |")
            w("|---|---:|")
            for k, nice in METRICS:
                if k in m and m[k] is not None:
                    w("| %s | %s |" % (nice, fmt(m[k])))
            w("")
            w("Per-trade distribution:")
            w("")
            w("| | value |")
            w("|---|---:|")
            for k, nice in DIST:
                if k in d and d[k] is not None:
                    w("| %s | %s |" % (nice, fmt(d[k])))
            w("")
            w("*%s*" % WHAT[b][1])
            w("")
        # the one comparison that matters, restated at the end of each era
        b, c = e["sets"]["BOOK"], e["sets"]["CELL"]
        w("### %s - BOOK vs CELL, the only comparison worth making" % label)
        w("")
        w("| | BOOK | CELL |")
        w("|---|---:|---:|")
        w("| trades | %s | %s |" % (fmt(b["n"]), fmt(c["n"])))
        w("| win rate %% | %s | %s |" % (fmt(b["wr"]), fmt(c["wr"])))
        w("| mean R | %s | %s |" % (fmt(b["avgR"]), fmt(c["avgR"])))
        w("| **median R** | **%s** | **%s** |" % (fmt(b["median"]), fmt(c["median"])))
        w("| profit factor | %s | %s |" % (fmt(b["pf"]), fmt(c["pf"])))
        w("| max drawdown | %s | %s |" % (fmt(b["max_dd"]), fmt(c["max_dd"])))
        w("| longest losing run | %s | %s |" % (fmt(b["max_streak"]), fmt(c["max_streak"])))
        w("")
        w("The cell wins %+.2fR of mean over the book on a %+.1f point win-rate gap."
          % (c["avgR"] - b["avgR"], c["wr"] - b["wr"]))
        w("That gap is not enough to produce it. It comes from the 90th percentile")
        w("trade, and the cell's **median** trade is %s the book's."
          % ("worse than" if c["median"] < b["median"] else "better than"))
        w("")

    text = "\n".join(out) + "\n"
    if "--write" in sys.argv:
        OUT.write_text(text, encoding="utf-8")
        print("wrote %s" % OUT.name)
    else:
        print(text)
    print("Nothing adopted. No pins changed. Shipping config untouched.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())